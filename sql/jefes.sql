SELECT
    j.OBJECTID,
    TRIM(j.NOMBRE) AS NOMBRE,
    LOWER(TRIM(j.CORREO)) AS CORREO,
    CASE
        WHEN UPPER(TRIM(j.REGION)) = 'ORIENTE CRENTRO'
         AND UPPER(TRIM(j.COD_REGION)) = 'ORC'
        THEN 'ORIENTE CENTRO'
        ELSE UPPER(TRIM(j.REGION))
    END AS REGION
FROM SDEUSR.M_JEFES_PRODUCCION_CANIA j
ORDER BY j.OBJECTID