WITH partes AS (
    SELECT m.REGION,
           CAST(m.C_FINCA AS NUMBER(9)) AS C_FINCA,
           TRIM(m.FINCA) AS FINCA,
           m.CODIGO_MODULO,
           m.TIPO_RIEGO,
           m.CANTIDAD_PERSONAL,
           ROW_NUMBER() OVER (
               PARTITION BY m.CODIGO_MODULO, m.C_FINCA,
                            m.SHAPE.AREA, m.SHAPE.MINX,
                            m.SHAPE.MINY, m.SHAPE.NUMPTS
               ORDER BY m.OBJECTID
           ) AS COPIA
      FROM SDEUSR.MAESTRO_MODULOS_RIEGO m
     WHERE m.CODIGO_MODULO IS NOT NULL
)
SELECT REGION,
       C_FINCA,
       FINCA,
       CODIGO_MODULO,
       LISTAGG(DISTINCT TIPO_RIEGO, ' / ')
           WITHIN GROUP (ORDER BY TIPO_RIEGO) AS TIPO_RIEGO,
       CAST(SUM(CANTIDAD_PERSONAL) AS NUMBER(6)) AS PERSONAS_ASIGNADAS
  FROM partes
 WHERE COPIA = 1
 GROUP BY REGION, C_FINCA, FINCA, CODIGO_MODULO
 ORDER BY REGION, FINCA, CODIGO_MODULO